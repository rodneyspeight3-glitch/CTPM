const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const {fixture}=require('./fixture.cjs');
(async () => {
 const app=await fixture();
 const response=await fetch(app.base+'/api/login',{method:'POST',headers:{'Content-Type':'application/json',Origin:app.base},body:JSON.stringify(app.credentials)});
 const cookie=response.headers.get('set-cookie').split(';')[0];
 for(const role of ['tenant','agent']){await fetch(app.base+'/api/admin/users',{method:'POST',headers:{'Content-Type':'application/json',Origin:app.base,Cookie:cookie},body:JSON.stringify({name:'Test '+role,email:role+'@example.test',password:app.credentials.password,role})});}
 const browser = await chromium.launch({headless:true,executablePath:process.env.CHROMIUM_PATH || '/usr/bin/chromium',args:['--no-sandbox']});
 const page = await browser.newPage({viewport:{width:1440,height:1100}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto(app.base);
 await page.getByRole('heading',{name:'It’s good to have you here.'}).waitFor();
 await page.setViewportSize({width:390,height:844});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
 await page.screenshot({path:'/tmp/come-together-login-mobile.png',fullPage:true});
 await page.setViewportSize({width:1440,height:1000});
 await page.screenshot({path:'/tmp/come-together-login.png',fullPage:true});
 await page.locator('[name="email"]').fill('tenant@example.test');
 await page.locator('[name="password"]').fill('wrong');
 await page.locator('#sign-in').click();
 await page.locator('#login-error').filter({hasText:'incorrect'}).waitFor();
 await page.locator('[name="password"]').fill(app.credentials.password);
 await page.locator('#toggle-password').click();
 assert.equal(await page.locator('[name="password"]').getAttribute('type'),'text');
 await page.locator('#toggle-password').click();
 await page.locator('#sign-in').click();
 await page.getByRole('heading',{name:'Good things come together.'}).waitFor();
 await page.locator('#account-name').filter({hasText:'Test tenant'}).waitFor();
 assert.equal(await page.locator('#team-nav').isVisible(),false);
 assert.equal(await page.locator('#featured .property-card').count(),3);
 await page.locator('[data-page="homes"]').click();
 await page.locator('#search').fill('Willow');
 assert.equal(await page.locator('#all-homes .property-card').count(),1);
 await page.locator('#beds').selectOption('1');
 assert.equal(await page.locator('#empty-homes').isVisible(),true);
 await page.locator('#search').fill('');
 assert.equal(await page.locator('#all-homes .property-card').count(),1);
 await page.locator('#all-homes [data-property]').click();
 await page.locator('#modal-content').getByRole('heading',{name:'The Oakwood',exact:true}).waitFor();
 await page.locator('#close-modal').click();
 await page.locator('[data-page="requests"]').click();
 await page.locator('#request-page-button').click();
 await page.locator('[name="title"]').fill('Leaking faucet <test>');
 await page.locator('textarea[name="description"]').fill('Kitchen faucet drips overnight.');
 await page.getByRole('button',{name:'Save demo request'}).click();
 assert.equal(await page.locator('.request-row').count(),1);
 assert.equal(await page.locator('.request-row h3').textContent(),'Leaking faucet <test>');
 await page.reload();
 await page.locator('[data-page="requests"]').click();
 assert.equal(await page.locator('.request-row').count(),1);
 await page.locator('[data-remove]').click();
 assert.equal(await page.locator('.request-row').count(),0);
 await page.locator('[data-page="overview"]').click();
 await page.locator('#payment').click();
 assert.match(await page.locator('#modal-content').textContent(),/connects a secure payment provider/);
 await page.keyboard.press('Escape');
 await page.locator('#toast').evaluate(el=>el.style.display='none');
 await page.locator('#payment').blur();
 await page.evaluate(async()=>{await Promise.all([...document.querySelectorAll('#featured img')].map(img=>img.decode().catch(()=>{})))});
 assert.equal(await page.locator('#featured img').evaluateAll(images=>images.every(img=>img.complete&&img.naturalWidth>0)),true);
 await page.screenshot({path:'/tmp/come-together-desktop.png',fullPage:true});
 await page.setViewportSize({width:390,height:844});
 await page.screenshot({path:'/tmp/come-together-mobile.png',fullPage:true});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
 assert.deepEqual(errors,[]);
 console.log('PASS: listings, filters, details, maintenance create/persist/delete, payments disclosure, mobile overflow, no browser errors.');
 await page.locator('#logout').click();
 await page.waitForURL('**/login');
 for(const role of ['agent','admin']){
  await page.locator('input[name="role"][value="'+role+'"]').check();
  await page.locator('[name="email"]').fill(role+'@example.test');
  await page.locator('[name="password"]').fill(app.credentials.password);
  await page.locator('#sign-in').click();
  await page.locator('#portal-title').filter({hasText:role==='admin'?'Admin portal':'Agent portal'}).waitFor();
  assert.equal(await page.locator('#team-nav').isVisible(),role==='admin');
  if(role==='admin'){
   await page.locator('#team-nav').click();
   await page.locator('#team-list .request-row').first().waitFor();
   assert.equal(await page.locator('#team-list .request-row').count(),3);
   await page.locator('#create-account').click();
   await page.locator('#create-user-form [name="name"]').fill('New Resident');
   await page.locator('#create-user-form [name="email"]').fill('new@example.test');
   await page.locator('#create-user-form [name="password"]').fill(app.credentials.password);
   await page.locator('#create-user-form button').click();
   await page.locator('#team-list').getByRole('heading',{name:'New Resident'}).waitFor();
  }
  await page.locator('#logout').click();await page.waitForURL('**/login');
 }
 assert.deepEqual(errors,[]);
 console.log('PASS: shared login, validation, tenant/agent/admin routing, admin account creation, sign-out, mobile login.');
 await browser.close();await app.cleanup();
})().catch(e=>{console.error(e);process.exit(1)});
